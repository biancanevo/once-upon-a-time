LANGUAGE_NAME_MAP = {
    "en": "English",
    "es": "Spanish",
    "it": "Italian",
    "fr": "French",
    "de": "German",
    "pt": "Portuguese",
    "nl": "Dutch",
    "ru": "Russian",
    "zh": "Chinese",
    "ja": "Japanese",
}

def get_translations(language_code: str) -> dict:
    """
    Get translations for the specified language code.
    Fallback to English if language not found.
    Handles 'es-ES' -> 'es' mapping.
    """
    lang = language_code.split("-")[0].lower()
    return TRANSLATIONS.get(lang, TRANSLATIONS["en"])

def get_language_name(language_code: str) -> str:
    """
    Map language code to proper English name for LLM prompting.
    Example: 'es-ES' -> 'Spanish'
    """
    lang = language_code.split("-")[0].lower()
    return LANGUAGE_NAME_MAP.get(lang, "English")
